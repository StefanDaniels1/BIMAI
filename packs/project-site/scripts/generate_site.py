# ---------------------------------------------------------------- escaping
_MDX_SPECIAL = str.maketrans({"{": "\\{", "}": "\\}", "<": "&lt;", ">": "&gt;"})


def mdx_text(value) -> str:
    """Escape free text for MDX (no JSX, no expressions)."""
    return "" if value is None else str(value).translate(_MDX_SPECIAL)


def mdx_cell(value) -> str:
    """Escape text for a Markdown table cell."""
    return mdx_text(value).replace("|", "\\|").replace("\n", " ").strip() or "—"


def mdx_markdown(markdown: str) -> str:
    """Make a Markdown document safe to embed in MDX, keeping code blocks and inline code intact."""
    out, in_fence = [], False
    for line in markdown.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            out.append(line)
            continue
        if in_fence:
            out.append(line)
            continue
        parts = line.split("`")
        # even-indexed parts are outside inline code
        out.append("`".join(mdx_text(p) if i % 2 == 0 else p for i, p in enumerate(parts)))
    return "\n".join(out)


def mm(value) -> str:
    """Escape text for a quoted Mermaid label."""
    return re.sub(r"[<>{}\[\]]", "", str(value)).replace('"', "#quot;")


def short(value: str, limit: int = 48) -> str:
    """Shorten on a word boundary, for diagram labels."""
    value = str(value)
    if len(value) <= limit:
        return value
    return value[:limit].rsplit(" ", 1)[0].rstrip(",.;:") + "…"


def node_id(prefix: str, value: str) -> str:
    return prefix + re.sub(r"\W", "_", value)


# ---------------------------------------------------------------- loading
def _yaml(path: Path, default=None):
    if not path.exists():
        return default
    return yaml.safe_load(path.read_text(encoding="utf-8")) or default


def _front_matter(path: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    if text.startswith("---"):
        _, fm, body = text.split("---", 2)
        return yaml.safe_load(fm) or {}, body.strip()
    return {}, text.strip()


def load_project(root: Path) -> dict:
    b = root / ".bimai"
    if not (b / "project.yaml").exists():
        raise FileNotFoundError(f"No .bimai/project.yaml under {root}")
    seats = {}
    for seat_dir in sorted((b / "seats").glob("*/")):
        seat = _yaml(seat_dir / "seat.yaml", {}) or {}
        seat["id"] = seat_dir.name
        seat["tasks"] = _yaml(seat_dir / "tasks.yaml", []) or []
        seat["journal"] = [dict(_front_matter(p)[0], body=_front_matter(p)[1], file=p.name)
                           for p in sorted((seat_dir / "journal").glob("*.md"))]
        seats[seat_dir.name] = seat
    decisions = [dict(fm, body=body) for fm, body in (_front_matter(p) for p in sorted((b / "decisions").glob("*.md")))]
    meetings = []
    for m_dir in sorted((b / "meetings").glob("*/")):
        meta = _yaml(m_dir / "meeting.yaml", {}) or {}
        if meta.get("status") != "applied" or not (m_dir / "minutes.md").exists():
            continue  # pending meetings are not shown until the uploader has confirmed them
        meta["slug"] = m_dir.name
        meta["minutes"] = (m_dir / "minutes.md").read_text(encoding="utf-8")
        meetings.append(meta)
    handoffs = []
    for p in sorted((b / "positions").glob("*/handoffs/*.yaml")):
        handoffs.append(_yaml(p, {}))
    workflows = [_yaml(p, {}) for p in sorted((b / "workflows").glob("*.yaml"))]
    automations = [_yaml(p, {}) for p in sorted((b / "automations").glob("*.yaml"))]
    return {
        "root": root,
        "project": _yaml(b / "project.yaml", {}),
        "agreements": _yaml(b / "agreements.yaml", {}) or {},
        "people": (_yaml(b / "people.yaml", {}) or {}).get("people", []),
        "ownership": _yaml(b / "ownership.yaml", {}) or {},
        "seats": seats,
        "decisions": sorted(decisions, key=lambda d: str(d.get("date", "")), reverse=True),
        "meetings": sorted(meetings, key=lambda m: str(m.get("date", "")), reverse=True),
        "handoffs": sorted(handoffs, key=lambda h: str(h.get("date", "")), reverse=True),
        "workflows": workflows,
        "automations": automations,
    }


# ---------------------------------------------------------------- helpers
class Site:
    def __init__(self, data: dict, base_url: str, files_url: str, today: dt.date):
        self.d = data
        self.p = data["project"]
        self.lang = self.p.get("language", "en") if self.p.get("language") in STRINGS else "en"
        self.base = base_url.rstrip("/")
        self.files_url = files_url.rstrip("/")
        self.today = today
        self.people = {p["id"]: p for p in data["people"]}
        self.by_seat = {p.get("seat"): p for p in data["people"] if p.get("seat")}
        self.positions = data["ownership"].get("positions", {}) or {}
        self.cover = data["ownership"].get("cover", []) or []
        self.docs = {d["id"]: d for d in data["agreements"].get("source_documents", []) or []}

    def t(self, key: str, **kw) -> str:
        return STRINGS[self.lang][key].format(**kw)

    def url(self, page: str = "") -> str:
        return f"{self.base}/{page}".rstrip("/")

    def seat_name(self, seat: str) -> str:
        return self.by_seat.get(seat, {}).get("name", seat)

    def person_name(self, pid: str) -> str:
        return self.people.get(pid, {}).get("name") or self.seat_name(pid)

    def source(self, src: dict | None) -> str:
        if not src:
            return "—"
        doc = self.docs.get(src.get("doc"), {})
        title = doc.get("title", src.get("doc", ""))
        parts = [title]
        if src.get("page"):
            parts.append(f"p. {src['page']}")
        if src.get("section"):
            parts.append(f"§{src['section']}")
        return mdx_cell(" · ".join(str(p) for p in parts if p))

    def active_cover(self) -> list[dict]:
        out = []
        for c in self.cover:
            until = dt.date.fromisoformat(str(c["until"]))
            start = dt.date.fromisoformat(str(c.get("from", c["until"])))
            if until >= self.today and start <= self.today + dt.timedelta(days=14):
                out.append(c)
        return out

    def cron_human(self, cron: str) -> str:
        parts = str(cron).split()
        if len(parts) != 5:
            return mdx_text(cron)
        minute, hour, dom, month, dow = parts
        if not (minute.isdigit() and hour.isdigit() and dom == "*" and month == "*"):
            return f"`{cron}`"
        at = f"{int(hour):02d}:{int(minute):02d}"
        if dow == "1-5":
            return f"{self.t('weekdays')} {at}"
        if dow.isdigit():
            day = WEEKDAYS[self.lang][int(dow) % 7]
            return f"{day[0].upper() + day[1:]} {at}" if self.lang == "en" else f"{self.t('every')} {day} {at}"
        if dow == "*":
            return f"{'Daily' if self.lang == 'en' else 'Dagelijks'} {at}"
        return f"`{cron}`"

    def open_tasks(self) -> list[dict]:
        tasks = []
        for seat_id, seat in self.d["seats"].items():
            for task in seat["tasks"]:
                if task.get("status", "open") != "done":
                    tasks.append(dict(task, seat=seat_id))
        return sorted(tasks, key=lambda x: str(x.get("due", "9999")))


def page(title: str, description: str, body: str) -> str:
    fm = f"---\ntitle: {json.dumps(title, ensure_ascii=False)}\ndescription: {json.dumps(description, ensure_ascii=False)}\n---\n\n"
    return fm + body.strip() + "\n"


def table(headers: list[str], rows: list[list]) -> str:
    if not rows:
        return ""
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def facts_list(items: list[tuple[str, object]], escape: bool = True) -> str:
    """Label/value pairs as a bulleted list (reads better than a two-column table without headers)."""
    return "\n".join(f"- **{label}:** {(mdx_text(value) if escape else str(value)).strip()}" for label, value in items if value)


def stat_cards(items: list[tuple[int, str]]) -> str:
    cards = "\n".join(f"  <Card title={json.dumps(str(n))} description={json.dumps(label, ensure_ascii=False)} />" for n, label in items)
    return "<Cards>\n" + cards + "\n</Cards>"


def callout(text: str, kind: str = "info") -> str:
    return f'<Callout type="{kind}">\n{text}\n</Callout>'


def mermaid(lines: list[str]) -> str:
    return "```mermaid\n" + "\n".join(lines) + "\n```"


# ---------------------------------------------------------------- pages
def page_overview(s: Site) -> str:
    p, a = s.p, s.d["agreements"]
    notes = []
    if p.get("demo"):
        notes.append(callout(s.t("demo_note"), "warn"))
    facts = facts_list([(s.t("goal"), p.get("goal")), (s.t("phase"), p.get("phase")),
                        (s.t("contract"), p.get("contract")), (s.t("client"), p.get("client"))])
    internal = [x for x in s.d["people"] if not x.get("external")]
    agents = sum(len(seat.get("team", [])) for seat in s.d["seats"].values())
    open_handoffs = [h for h in s.d["handoffs"] if h.get("status") != "done"]
    glance = stat_cards([
        (len(internal), s.t("people_n")), (len(s.positions), s.t("positions_n")), (agents, s.t("agents_n")),
        (len(s.d["decisions"]), s.t("decisions_n")), (len(s.d["meetings"]), s.t("meetings_n")),
        (len(s.open_tasks()), s.t("open_tasks_n")), (len(open_handoffs), s.t("open_handoffs_n")),
    ])
    upcoming = [m for m in a.get("milestones", []) or [] if dt.date.fromisoformat(str(m["date"])) >= s.today][:3]
    milestones = table([s.t("milestone"), s.t("date")], [[mdx_cell(m["name"]), m["date"]] for m in upcoming])
    cards = [f'  <Card title={json.dumps(s.t(k))} href="{s.url(slug)}" />' for k, slug in [
        ("people", "people"), ("ai_teams", "ai-teams"), ("how_we_work", "how-we-work"),
        ("agreements", "agreements"), ("decisions", "decisions"), ("this_week", "this-week")]]
    links = [f'  <Card title={json.dumps(l["title"], ensure_ascii=False)} href={json.dumps(l["url"])} description={json.dumps(l.get("description", ""), ensure_ascii=False)} />'
             for l in p.get("links", []) or []]
    for doc in s.docs.values():
        desc = json.dumps(f"{doc.get('title', '')} · {doc.get('date', '')}", ensure_ascii=False)
        links.append(f'  <Card title={json.dumps(s.t("bep_card"), ensure_ascii=False)} '
                     f'href="{s.files_url}/{Path(doc["file"]).name}" description={desc} />')
    body = "\n\n".join(notes + [
        facts,
        f"## {s.t('at_a_glance')}", glance,
        f"## {s.t('next_milestones')}", milestones or s.t("nothing_yet"),
        "<Cards>\n" + "\n".join(cards) + "\n</Cards>",
        f"## {s.t('links')}", "<Cards>\n" + "\n".join(links) + "\n</Cards>" if links else s.t("nothing_yet"),
        f"_{s.t('generated_note', date=s.today.isoformat())}_",
    ])
    return page(p.get("name", p.get("id", "Project")), mdx_text(p.get("phase", "")), body)


def page_people(s: Site) -> str:
    covers = {c["position"]: c for c in s.active_cover()}
    rows = []
    for pid, pos in s.positions.items():
        holders = []
        for seat in pos.get("held_by", []):
            name = mdx_cell(s.seat_name(seat))
            holders.append(f"{name} ({s.t('lead')})" if pos.get("lead") == seat and len(pos.get("held_by", [])) > 1 else name)
        scope = ", ".join(f"{k}: {v}" for k, v in (pos.get("scope") or {}).items())
        cover = covers.get(pid)
        cover_txt = f"{mdx_cell(s.seat_name(cover['by']))} → {cover['until']}" if cover else "—"
        rows.append([f"`{pid}`", mdx_cell(pos.get("role")), mdx_cell(scope), ", ".join(holders) or "—", cover_txt])
    lines = ["flowchart LR"]
    for pid, pos in s.positions.items():
        lines.append(f'  {node_id("P_", pid)}["{mm(pid)}"]')
        for seat in pos.get("held_by", []):
            lines.append(f'  {node_id("U_", seat)}(["{mm(s.seat_name(seat))}"]) --- {node_id("P_", pid)}')
    for c in s.active_cover():
        label = mm(s.t("covers", pos=c["position"], until=c["until"]))
        lines.append(f'  {node_id("U_", c["by"])} -.->|"{label}"| {node_id("P_", c["position"])}')
    owners = [[mdx_cell(r.replace("-", " ")), f"`{pid}`"] for pid, pos in s.positions.items() for r in pos.get("responsibilities", [])]
    team_rows = [[mdx_cell(x["name"]), mdx_cell(x.get("title")), mdx_cell(x.get("organization"))]
                 for x in s.d["people"] if not x.get("external")]
    ext_rows = [[mdx_cell(x["name"]), mdx_cell(x.get("title")), mdx_cell(x.get("organization"))]
                for x in s.d["people"] if x.get("external")]
    body = "\n\n".join([
        s.t("people_intro"),
        f"## {s.t('positions')}", table([s.t("position"), s.t("role"), s.t("scope"), s.t("held_by"), s.t("cover")], rows),
        mermaid(lines),
        f"## {s.t('who_owns_what')}", table([s.t("responsibility"), s.t("position")], owners),
        f"## {s.t('people')}", table([s.t("name"), s.t("title"), s.t("organization")], team_rows),
        f"## {s.t('external')}", table([s.t("name"), s.t("title"), s.t("organization")], ext_rows) or s.t("nothing_yet"),
    ])
    return page(s.t("people"), s.t("positions") + " · " + s.t("who_owns_what"), body)


def page_ai_teams(s: Site) -> str:
    parts = [s.t("teams_intro")]
    lines = ["flowchart LR"]
    for seat_id, seat in s.d["seats"].items():
        label = f"{s.seat_name(seat_id)} · {', '.join(seat.get('positions', []))}"
        lines.append(f'  subgraph {node_id("S_", seat_id)}["{mm(label)}"]')
        lines.append("    direction TB")
        for member in seat.get("team", []):
            emoji, name, *_ = ROLES.get(member["role"], ("🤖", member["role"], "", {}))
            lines.append(f'    {node_id("S_", seat_id + "_" + member["role"])}["{emoji} {mm(name)}"]')
        lines.append("  end")
    for h in s.d["handoffs"]:
        target = s.positions.get(h.get("to"), {})
        receiver = target.get("lead") or (target.get("held_by") or [None])[0]
        sender = (h.get("from") or {}).get("seat")
        if sender in s.d["seats"] and receiver in s.d["seats"]:
            label = f'{mm(s.t("handoff"))}: {mm(short(h.get("title", "")))}'
            lines.append(f'  {node_id("S_", sender)} -->|"{label}"| {node_id("S_", receiver)}')
    parts.append(mermaid(lines))
    for seat_id, seat in s.d["seats"].items():
        rows = []
        for member in seat.get("team", []):
            emoji, name, tier, what = ROLES.get(member["role"], ("🤖", member["role"], "", {}))
            rows.append([f"{emoji} {mdx_cell(name)}", mdx_cell(what.get(s.lang, "")), mdx_cell(member.get("why")), tier or "—"])
        heading = f"{mdx_text(s.seat_name(seat_id))} · " + ", ".join(f"`{p}`" for p in seat.get("positions", []))
        parts += [f"### {heading}", table([s.t("member"), s.t("what_it_does"), s.t("why"), s.t("model")], rows)]
    parts.append(f"## {s.t('handoffs_title')}")
    hrows = [[h.get("date", ""), mdx_cell(h.get("title")),
              f"{mdx_cell(s.seat_name((h.get('from') or {}).get('seat', '')))} ({mdx_cell(ROLES.get((h.get('from') or {}).get('role'), ('', (h.get('from') or {}).get('role', '')))[1])})",
              f"`{h.get('to')}`", s.t(h.get("status", "open")) if h.get("status") in ("open", "done") else mdx_cell(h.get("status"))]
             for h in s.d["handoffs"]]
    parts.append(table([s.t("date"), s.t("handoff"), s.t("from"), s.t("to"), s.t("status")], hrows) or s.t("no_handoffs"))
    return page(s.t("ai_teams"), s.t("teams_intro").split(".")[0] + ".", "\n\n".join(parts))


def workflow_mermaid(wf: dict) -> str:
    steps = wf.get("steps") or {}
    lines = ["flowchart LR" if len(steps) <= 6 else "flowchart TB"]  # long chains read better top to bottom
    for step_id, step in steps.items():
        nid = node_id("W_", step_id)
        many = " ×n" if step.get("foreach") else ""
        if "agent" in step:
            emoji, name, *_ = ROLES.get(step["agent"], ("🤖", step["agent"], "", {}))
            lines.append(f'  {nid}(["{mm(step_id)}{many}<br/>{emoji} {mm(name)}"])')
        elif "gate" in step:
            lines.append(f'  {nid}{{"✋ {mm(step_id)}"}}')
        elif "workflow" in step:
            lines.append(f'  {nid}[["{mm(step_id)}{many}<br/>↪ {mm(step["workflow"])}"]]')
        elif "script" in step:
            lines.append(f'  {nid}["{mm(step_id)}{many}<br/>🧮 script"]')
        else:
            lines.append(f'  {nid}["{mm(step_id)}{many}<br/>🔌 {mm(step.get("tool", ""))}"]')
        for need in step.get("needs", []) or []:
            lines.append(f"  {node_id('W_', need)} --> {nid}")
    return mermaid(lines)


def page_how_we_work(s: Site) -> str:
    p, a = s.p, s.d["agreements"]
    parts = [s.t("flow_intro"), mermaid([
        "flowchart LR",
        f'  U(["{mm(s.t("people"))}"]) --> C["🧭 Coordinator"]',
        '  C --> W["' + mm(s.t("workflows")) + '"]',
        '  W --> T["🔌 ACC · Revit · Civil 3D · files"]',
        '  W --> G{"✋ ' + mm(s.t("approvals")) + '"}',
        '  G --> U',
    ])]
    owners = ", ".join(mdx_text(s.person_name(o)) for o in p.get("rule_owners", []) or []) or "—"
    parts += [f"## {s.t('approvals')}", facts_list([
        (s.t("write_mode"), s.t(f"write_mode_{p.get('write_mode', 'read-only')}")),
        (s.t("rule_owners"), owners),
    ], escape=False)]
    coord = a.get("coordination")
    if coord:
        parts += [f"## {s.t('rhythm')}", f"{mdx_text(coord.get('description'))}\n\n{s.t('source')}: {s.source(coord.get('source'))}"]
    parts.append(f"## {s.t('workflows')}")
    for wf in s.d["workflows"]:
        parts += [f"### {mdx_text(wf.get('id'))}", mdx_text(wf.get("description", "")), workflow_mermaid(wf)]
