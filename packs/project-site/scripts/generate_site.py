def generate(project_root: Path, out_dir: Path, public_dir: Path | None = None, files_url: str | None = None,
             base_url: str = "/docs", today: dt.date | None = None) -> list[Path]:
    data = load_project(project_root)
    pid = data["project"].get("id", project_root.name)
    site = Site(data, base_url, files_url or f"/project-files/{pid}", today or dt.date.today())
    pages = {
        "index.mdx": page_overview(site),
        "people.mdx": page_people(site),
        "ai-teams.mdx": page_ai_teams(site),
        "how-we-work.mdx": page_how_we_work(site),
        "agreements.mdx": page_agreements(site),
        "decisions.mdx": page_decisions(site),
        "this-week.mdx": page_this_week(site),
        **meeting_pages(site),
    }
    title = data["project"].get("name", pid) + (" (demo)" if data["project"].get("demo") else "")
    pages["meta.json"] = json.dumps({"title": title, "pages": ["index", "people", "ai-teams", "how-we-work",
                                                              "agreements", "decisions", "meetings", "this-week"]},
                                    indent=2, ensure_ascii=False)
    if out_dir.exists():
        shutil.rmtree(out_dir)
    written = []
    for rel, content in pages.items():
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    if public_dir is not None:
        target = public_dir
        if target.exists():
            shutil.rmtree(target)
        target.mkdir(parents=True)
        for doc in site.docs.values():
            src = project_root / ".bimai" / doc["file"]
            if src.exists():
                shutil.copy2(src, target / src.name)
                written.append(target / src.name)
    return written


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("project_root", type=Path)
    ap.add_argument("content_out_dir", type=Path)
    ap.add_argument("--public-dir", type=Path)
    ap.add_argument("--files-url")
    ap.add_argument("--base-url", default="/docs")
    ap.add_argument("--today", type=dt.date.fromisoformat)
    args = ap.parse_args(argv[1:])
    try:
        written = generate(args.project_root, args.content_out_dir, args.public_dir, args.files_url, args.base_url, args.today)
    except FileNotFoundError as exc:
        print(json.dumps({"ok": False, "error": "invalid_input", "message": str(exc)}))
        return 1
    print(json.dumps({"ok": True, "files": [str(p) for p in written]}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
